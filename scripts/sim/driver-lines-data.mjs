// scripts/sim/data/learn/driver-lines.json (Actions: learn/fetch-driver-lines.mjs) -> worker/lapsim/driver-lines-data.js (what the page
// reads) and docs/lapsim-driver-lines.md. Kept: drivers whose fit lap is representative (error with the field line under 25 %); a test
// counts only when that lap is representative too.
import {readFileSync, writeFileSync} from 'node:fs';
const J = JSON.parse(readFileSync('scripts/sim/data/learn/driver-lines.json', 'utf8'));
const r3 = x => +x.toFixed(3), mean = a => a.length ? +(a.reduce((x, y) => x + y, 0) / a.length).toFixed(2) : null, tracks = {}, rows = [];
const keepTest = t => t && t[0] < 25 ? t : null;
const tidy = n => String(n || '').replace(/[A-ZÀ-Þ][A-ZÀ-Þ'-]+/g, w => w[0] + w.slice(1).toLowerCase()); // Al Kamel writes family names in capitals
for (const [id, ys] of Object.entries(J.f1)) for (const [y, t] of Object.entries(ys)) for (const [code, r] of Object.entries(t.drivers)) {
  const test = keepTest(r.test && [r.test.before, r.test.after]);
  ((((tracks[id] ||= {}).f1 ||= {})[y] ||= {drivers: {}}).drivers[code] = {w: r.w, name: r.name, id: r.id, team: r.team, fit: [r.fitBefore, r.fitAfter], test});
  rows.push({kind: 'F1 ' + y, id, fit: [r.fitBefore, r.fitAfter], test});
}
for (const [id, bs] of Object.entries(J.endurance)) for (const [b, t] of Object.entries(bs)) for (const [key, r] of Object.entries(t.drivers)) {
  const W = 10, w = Array.from({length: W}, (_, k) => { const f = (k + 0.5) / W; return r.w3[f < t.cuts[0] ? 0 : f < t.cuts[1] ? 1 : 2]; }), test = keepTest(r.test);
  ((((tracks[id] ||= {}).end ||= {})[b] ||= {sectors: t.atlas, drivers: {}}).drivers[key] = {w, name: tidy(r.name), manufacturer: r.manufacturer, team: r.team, series: r.series, season: r.season, fit: r.fit, test});
  rows.push({kind: b.toUpperCase(), id, fit: r.fit, test});
}
const groups = [...new Set(rows.map(r => r.kind))].sort(), sum = g => { const R = rows.filter(r => r.kind === g), T = R.filter(r => r.test); return {drivers: R.length, tracks: new Set(R.map(r => r.id)).size, fit: [mean(R.map(r => r.fit[0])), mean(R.map(r => r.fit[1]))], test: [mean(T.map(r => r.test[0])), mean(T.map(r => r.test[1]))], testBetter: T.filter(r => r.test[1] < r.test[0]).length, testN: T.length}; };
// per track and class too: a group whose own drivers (5 or more tested) are not better than the field line on unseen laps is left out
const dropped = [];
for (const [id, t] of Object.entries(tracks)) for (const [k, grp] of [...Object.entries(t.f1 || {}).map(([y, v]) => ['F1 ' + y, v]), ...Object.entries(t.end || {}).map(([b, v]) => [b.toUpperCase(), v])]) {
  const T = Object.values(grp.drivers).filter(r => r.test); if (T.length < 5) continue;
  const a = T.reduce((q, r) => q + r.test[0], 0) / T.length, b = T.reduce((q, r) => q + r.test[1], 0) / T.length;
  if (b >= a) { dropped.push(id + ' ' + k + ` (${a.toFixed(2)} → ${b.toFixed(2)} %, ${T.length} drivers)`); if (k.startsWith('F1 ')) delete t.f1[k.slice(3)]; else delete t.end[k.toLowerCase()]; }
}
const summary = Object.fromEntries(groups.map(g => [g, sum(g)]));
// gate (physics rule 2.1): a group's driver lines are shown only when, on laps the fit did not see, they beat the field line on
// average and for more than half of the drivers; otherwise the driver differences are noise and the page keeps the car line
for (const g of groups) summary[g].shown = summary[g].test[1] < summary[g].test[0] && summary[g].testBetter > summary[g].testN / 2;
const hide = g => !summary[g].shown;
for (const t of Object.values(tracks)) {
  for (const [y, v] of Object.entries(t.f1 || {})) if (hide('F1 ' + y)) delete t.f1[y];
  for (const b of Object.keys(t.end || {})) if (hide(b.toUpperCase())) delete t.end[b];
}
writeFileSync('worker/lapsim/driver-lines-data.js', '// Generated by scripts/sim/driver-lines-data.mjs from scripts/sim/data/learn/driver-lines.json. Do not edit by hand.\nexport const lapsimDriverLines=' + JSON.stringify({generatedAt: J.generatedAt, summary, tracks}) + ';\n');
const amb = J.ambiguous || [], multi = Object.values(J.people).filter(p => p.aliases.length > 1);
writeFileSync('docs/lapsim-driver-lines.md', `# Racing line per driver (every series)

Generated ${J.generatedAt} by \`scripts/sim/learn/fetch-driver-lines.mjs\` (GitHub Actions) and \`scripts/sim/driver-lines-data.mjs\`.

No public source gives a measured driven line, so each driver's line is **estimated**:

- **F1**: from the speed trace of the driver's best clean dry qualifying lap (TracingInsights), judged on the minimum speed of every
  official corner. 10 windows of least-curvature / shortest-path share.
- **Endurance (LMH, LMDh, GT3; WEC, IMSA, ELMS, Asian LMS, qualifying 2024-2026), Formula E (Gen2, Gen3, Gen3 Evo; Al Kamel
  qualifying) and SRO GT3 (Timing71 laps that name the driver)**: no speed trace, only the three sector times. Sector positions:
  tobi/track-atlas when they put the field's sector shares within 1.5 % of the lap on this layout; otherwise estimated (the cut pair
  that makes the car line's simulated shares match the field's median shares). One share per timing sector.

Both first fit the **field line** (median of all drivers at that track and class: what the track, the timing lines and the car model
explain), then each driver's difference from it. The test lap is the driver's next clean lap within 2 % of the best, not used in the fit;
"before" = field line, "after" = driver line. Error: F1 RMS of corner minimum speeds, endurance RMS of sector times, %, after one
common scale.

| Group | Tracks | Drivers | Fit lap, field → driver | Unseen lap, field → driver | Unseen lap better | Shown |
|---|---|---|---|---|---|---|
${groups.map(g => { const s = summary[g]; return `| ${g} | ${s.tracks} | ${s.drivers} | ${s.fit[0]} → ${s.fit[1]} | ${s.test[0]} → ${s.test[1]} | ${s.testBetter} / ${s.testN} | ${s.shown ? 'yes' : 'no: not better than the field line on unseen laps'} |`; }).join('\n')}

## Driver names across series

One id per person (\`scripts/sim/learn/drivers.mjs\`): accents, case, punctuation and word order are ignored ("Kevin ESTRE" = "Kévin Estre",
"ZHOU Guanyu" = "Guanyu Zhou"); an initial or a short first name ("K. Estre", "Alex Lynn" / "Alexander Lynn") joins a full name only when
exactly one known driver fits; F1 three-letter codes come with the full name from TracingInsights. ${Object.keys(J.people).length} people;
${multi.length} written in more than one way; ${amb.length} names left separate as ambiguous${amb.length ? ': ' + amb.slice(0, 20).map(a => a.name + ' (' + a.candidates.join(' / ') + ')').join(', ') : ''}.

Written more than one way (first 40): ${multi.slice(0, 40).map(p => p.aliases.join(' = ')).join('; ')}.

Track and class groups left out because their drivers were not better than the field line on unseen laps: ${dropped.join(', ') || 'none'}.

2026 races not held (Bahrain, Saudi Arabia): the TracingInsights folders of those events are not a qualifying on the layout (field error above 50 %), so they give no driver lines.

Not possible with the data we have: **SRO GT3** (GT World Challenge, IGTC, British GT) per driver. The SRO result tables give one best
lap per car without sectors, and the Timing71 lap rows name the driver in only 54 of 775,064 GT3 rows (the rest carry a seat number).
SRO GT3 cars keep the car line; their drivers appear only where they also raced WEC, IMSA, ELMS or Asian LMS. Formula E driver lines
were fitted but did not beat the field line on unseen laps, so the page keeps the car line for Formula E (table above).

Limits: the remaining error is mostly the car model, the track geometry and (endurance) the sector positions, not the line; the
field line takes that part, and the unseen-lap check shows whether a driver's own difference is real or noise.
`);
