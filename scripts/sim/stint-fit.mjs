// Hypercar stint energy model, checked on real races. Real energy per lap = BoP stint energy (MJ) /
// laps of a full stint (the longest green stint a car repeats, i.e. a full virtual energy tank). The
// simulated qualifying-pace driveshaft energy per lap (stint-energy.js) is scaled by one race factor k
// (lift-and-coast, race pace), fitted on all events and tested leave-one-event-out. 2026 BoP is not
// published: its stint energy is estimated from the real stint length and the model energy per lap.
// In: scripts/sim/data/wec-stints.json (wec-stints.mjs, Al Kamel), worker/lapsim/wec-bop-data.js.
// Out: worker/lapsim/stint-data.js.
import {readFileSync, writeFileSync} from 'node:fs';
import {lapsimKernel} from '../../worker/lapsim/kernel.js';
import {lapsimTracks} from '../../worker/lapsim/tracks-data.js';
import {carsFor, realConditions} from '../../worker/lapsim/scenario.js';
import {lapsimWecBop} from '../../worker/lapsim/wec-bop-data.js';
import {driveEnergyJ} from '../../worker/lapsim/stint-energy.js';

const K = lapsimKernel(), stints = JSON.parse(readFileSync('scripts/sim/data/wec-stints.json', 'utf8'));
const LMH = /toyota|ferrari|peugeot|aston|glickenhaus|isotta/i, brand = s => String(s).split(/\s+/)[0].toLowerCase();
const median = a => { const s = [...a].sort((x, y) => x - y); return s.length ? (s[(s.length - 1) >> 1] + s[s.length >> 1]) / 2 : NaN; };
// a full stint: the longest green stint length the car ran at least twice (±1 lap)
const fullStint = s => { const c = [...s].sort((a, b) => b - a).filter(x => x >= 5); return c.find(x => c.filter(y => Math.abs(y - x) <= 1).length >= 2) ?? null; };
const simLap = {};
const lapMJ = (id, cls) => simLap[id + cls] ??= (() => { const c = carsFor(id)['wec-' + cls], tr = K.trackFromData(lapsimTracks[id]), env = K.conditionsFromWeather(realConditions(id)?.['wec-' + cls] || {}); tr.mu.fill(c.grip); const r = K.simulateLap(tr, c.car, env); return driveEnergyJ(tr, c.car, env, r.v) / 1e6; })();

const rows = [], est = [];
for (const [year, tracks] of Object.entries(stints)) for (const [id, ev] of Object.entries(tracks)) {
  if (!lapsimTracks[id]) continue;
  // event reference: the typical long stint (2nd longest stint of each car, any flag); a "full stint" far
  // below it is a flag-shortened artefact (e.g. Spa 2025) and is dropped
  const ref = median(Object.values(ev.cars).map(c => [...c.allStints].sort((x, y) => y - x)[1]).filter(Number.isFinite)), by = {};
  for (const c of Object.values(ev.cars)) { const f = fullStint(c.stints); if (f && f >= 0.8 * ref) (by[brand(c.manufacturer)] ||= []).push(f); }
  for (const [b, f] of Object.entries(by)) {
    const laps = median(f), cls = LMH.test(b) ? 'lmh' : 'lmdh', sim = lapMJ(id, cls);
    const bop = Object.entries(lapsimWecBop[id]?.[year]?.cars || {}).find(([n]) => brand(n) === b)?.[1];
    if (bop?.MJ) rows.push({year, id, brand: b, cls, laps, MJ: bop.MJ, real: bop.MJ / laps, sim});
    else est.push({year, id, brand: b, cls, laps, sim});
  }
}
const kOf = rs => median(rs.map(r => r.real / r.sim));
const k = kOf(rows), events = [...new Set(rows.map(r => r.year + r.id))];
// leave one event out: predicted stint laps vs real
const err = rows.map(r => { const kk = kOf(rows.filter(x => x.year + x.id !== r.year + r.id)); return (r.MJ / (kk * r.sim) - r.laps) / r.laps * 100; });
const rms = Math.sqrt(err.reduce((s, x) => s + x * x, 0) / err.length);
const out = {generatedAt: new Date().toISOString(), k: +k.toFixed(4), test: {rows: rows.length, events: events.length, rmsPct: +rms.toFixed(2)}, tracks: {}};
for (const r of rows) ((out.tracks[r.id] ||= {})[r.year] ||= {})[r.brand] = {laps: r.laps, MJ: r.MJ, lapMJ: +r.real.toFixed(3), simMJ: +r.sim.toFixed(3), basis: 'bop'};
for (const r of est) ((out.tracks[r.id] ||= {})[r.year] ||= {})[r.brand] = {laps: r.laps, MJ: Math.round(r.laps * k * r.sim), lapMJ: +(k * r.sim).toFixed(3), simMJ: +r.sim.toFixed(3), basis: 'estimated'};
writeFileSync('worker/lapsim/stint-data.js', '// Generated by scripts/sim/stint-fit.mjs: Hypercar stint energy per event and manufacturer\nexport const lapsimStints = ' + JSON.stringify(out) + ';\n');
console.log(`k ${k.toFixed(3)} (race energy per lap / simulated), ${rows.length} BoP rows over ${events.length} events, leave-one-event-out stint-length RMS ${rms.toFixed(2)}%; ${est.length} estimated (no published BoP)`);
for (const r of rows) console.log(r.year, r.id.padEnd(18), r.brand.padEnd(9), r.cls, 'laps', r.laps, 'real', r.real.toFixed(2), 'sim', r.sim.toFixed(2), 'ratio', (r.real / r.sim).toFixed(3));
