// F1 qualifying sessions with rain (owner 2026-11-22): the dry fit leaves them out, so the page used to show a dry prediction in another
// season's weather. Now the default is the real session (its real pole and weather, reproduced exactly; real laps are never changed), and
// a dry pole estimate is shown next to it, labelled model:
//   dry = (1 − w) × model prediction (calibration seasons[2026].predictions) + w × that weekend's fastest dry race lap × median(pole / race
//   best) of the season's dry fitted events. w = s_model² / (s_model² + s_race²) from the two held-out errors (inverse variance).
// node scripts/sim/learn/wet-quali.mjs --write   (lapsim-data runs it after calibration)
import {readFileSync, writeFileSync} from 'node:fs';
import {lapsimCalibration as C} from '../../../worker/lapsim/calibration-data.js';
import {lapsimF1Poles as P} from '../../../worker/lapsim/f1-poles-data.js';
import {lapsimRaceRecords as R} from '../../../worker/lapsim/race-records-data.js';
const src = JSON.parse(readFileSync(new URL('../data/learn/f1-wet-quali.json', import.meta.url), 'utf8'));
const med = a => { const s = [...a].sort((x, y) => x - y), n = s.length; return n % 2 ? s[n >> 1] : (s[n / 2 - 1] + s[n / 2]) / 2; };
const rms = a => Math.sqrt(a.reduce((s, x) => s + x * x, 0) / a.length);
const out = {};
for (const y of ['2026']) {
  const S = C.seasons?.[y]; if (!S) continue;
  const rows = Object.entries(S.tracks).filter(([, t]) => !t.weather?.rain).map(([id, t]) => ({id, pole: P[id]?.[y]?.lap ?? t.realLap, race: R.f1?.[id]?.[y]?.lap})).filter(r => r.pole && r.race);
  // held-out errors (%) on the season's held-out tracks: model as fitted, race ratio leave-one-out
  const ho = (S.holdout?.tracks || []).map(h => ({h, r: rows.find(r => r.id === h.track)})).filter(x => x.r);
  const eM = ho.map(({h, r}) => h.errorSec / r.pole * 100);
  const eR = ho.map(({r}) => (r.race * med(rows.filter(q => q !== r).map(q => q.pole / q.race)) - r.pole) / r.pole * 100);
  const sM = rms(eM), sR = rms(eR), w = sM ** 2 / (sM ** 2 + sR ** 2), ratio = med(rows.map(r => r.pole / r.race));
  const eB = ho.map(({h, r}, i) => ((1 - w) * (r.pole + h.errorSec) + w * (r.pole * (1 + eR[i] / 100)) - r.pole) / r.pole * 100);
  const test = {n: ho.length, modelPct: +sM.toFixed(3), racePct: +sR.toFixed(3), blendPct: +rms(eB).toFixed(3), wRace: +w.toFixed(3), ratio: +ratio.toFixed(5)};
  for (const [id, ys] of Object.entries(src.events)) { const e = ys[y]; if (!e) continue;
    const model = S.predictions?.[id]?.lap, race = R.f1?.[id]?.[y]?.lap;
    const dry = model && race ? (1 - w) * model + w * race * ratio : model ?? (race ? race * ratio : null);
    (out[id] ||= {})[y] = {...e, real: true, dry: dry ? {lap: +dry.toFixed(3), pct: test.blendPct, model: model ?? null, raceLap: race ?? null, wRace: test.wRace, ratio: test.ratio} : null};
  }
  out._test = {...(out._test || {}), [y]: test};
}
if (process.argv.includes('--write')) writeFileSync('worker/lapsim/f1-wet-quali-data.js', '// Generated by scripts/sim/learn/wet-quali.mjs. Do not edit by hand.\nexport const lapsimF1WetQuali = ' + JSON.stringify(out) + ';\n');
console.log(JSON.stringify(out._test), Object.keys(out).filter(k => k[0] !== '_').map(k => `${k} real ${out[k]['2026'].lap} dry ${out[k]['2026'].dry?.lap}`).join('; '));
