// Each F1 driver's real qualifying lap per track and season (owner 2026-11-22: picking a driver in the LapSim driver menu shows
// that driver's real lap of that event's qualifying, in that session's weather). Fastest valid lap of the driver's whole
// qualifying (any segment, not deleted, sectors adding up to the lap); wet laps kept with their compound. Real data, read-only.
// In: TracingInsights season repos (sparse clone, LAPSIM_TI_DIR, as f1-poles.mjs). Out: worker/lapsim/f1-driver-quali-data.js
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {tiTrack} from './ti-races.mjs';

const ROOT = process.env.LAPSIM_TI_DIR || '.cache/ti', YEARS = (process.env.LAPSIM_POLE_YEARS || '2025,2026').split(',');
const num = v => v === 'None' || v == null || !Number.isFinite(+v) ? null : +v;
const out = {};
for (const y of YEARS) {
  if (!existsSync(join(ROOT, y))) continue;
  for (const ev of readdirSync(join(ROOT, y)).filter(e => /Grand Prix$/.test(e))) {
    const dir = join(ROOT, y, ev, 'Qualifying'); if (!existsSync(dir)) continue;
    const rows = {};
    for (const drv of readdirSync(dir)) {
      const f = join(dir, drv, 'laptimes.json'); if (!existsSync(f)) continue;
      const d = JSON.parse(readFileSync(f, 'utf8'));
      d.time.forEach((t, i) => {
        const lap = num(t), s = [num(d.s1[i]), num(d.s2[i]), num(d.s3[i])];
        if (lap == null || d.del?.[i] || s.some(x => x == null) || Math.abs(s[0] + s[1] + s[2] - lap) > 0.002) return;
        if (!rows[drv] || lap < rows[drv].lap) rows[drv] = {lap, sectors: s, compound: d.compound?.[i] || null, seg: d.qs?.[i] || ''};
      });
    }
    if (Object.keys(rows).length) (out[tiTrack(ev, +y)] ||= {})[y] = rows;
  }
}
writeFileSync('worker/lapsim/f1-driver-quali-data.js', '// Generated by scripts/sim/f1-driver-quali.mjs from TracingInsights qualifying laps: each driver\'s real qualifying lap per track and season\nexport const lapsimF1DriverQuali = ' + JSON.stringify(out) + ';\n');
for (const [t, ys] of Object.entries(out)) console.log(t.padEnd(20), Object.entries(ys).map(([y, r]) => `${y} ${Object.keys(r).length} drivers`).join('  '));
