// Pirelli dry compound nominations (HARD, MEDIUM, SOFT as C-numbers) per F1 race, from
// .cache/compounds.json ({year: {"Event Grand Prix": ["C3","C4","C5"]}}, collected from Pirelli and
// formula1.com releases) to worker/lapsim/compounds-data.js ({track: {year: [hard, medium, soft]}}).
import {readFileSync, writeFileSync} from 'node:fs';
import {tiTrack} from './ti-races.mjs';

const src = JSON.parse(readFileSync(process.argv[2] || '.cache/compounds.json', 'utf8')), out = {};
for (const [year, events] of Object.entries(src)) for (const [event, c] of Object.entries(events)) {
  if (!/^C[1-6]$/.test(c[0]) || c.length !== 3) continue;
  const id = tiTrack(event, +year), slot = (out[id] ||= {});
  slot[slot[year] ? year + '-2' : year] = c; // two races at one track in a season (2020)
}
writeFileSync('worker/lapsim/compounds-data.js', '// Generated by scripts/sim/compounds.mjs: Pirelli C-number nominations [hard, medium, soft] per track and season.\nexport const lapsimCompounds = ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length, 'tracks');
